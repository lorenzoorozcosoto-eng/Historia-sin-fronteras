/* =====================================================
   VARIABLES DEL JUEGO
===================================================== */

let temaActual = "gastronomia";

let puntos = 0;

let vidas = 3;

let respuestaContestada = false;

let retosCompletados = 0;

let respuestasCorrectas = 0;

const totalRetos = Object.keys(temas).length;


/* =====================================================
   CAMBIAR TEMA
===================================================== */

function cambiarTema(nombre, boton = null) {

    const tema = temas[nombre];

    if (!tema) {
        return;
    }

    temaActual = nombre;

    respuestaContestada = false;


    /* TÍTULO */

    document.getElementById("iconoTema").textContent =
        tema.icono;

    document.getElementById("tituloTema").textContent =
        tema.titulo;

    document.getElementById("subtituloTema").textContent =
        tema.subtitulo;


    /* INFORMACIÓN */

    document.getElementById("mensajeRobot").textContent =
        tema.mensaje;

    document.getElementById("imagenTema").src =
        tema.imagen;

    document.getElementById("datoTema").textContent =
        tema.dato;

    document.getElementById("regionesTema").textContent =
        tema.regiones;

    document.getElementById("sobreTexto").textContent =
        tema.sobre;


    /* PREGUNTA */

    document.getElementById("pregunta").textContent =
        tema.pregunta;


    /* RESULTADO */

    const resultado =
        document.getElementById("resultado");

    resultado.textContent = "";

    resultado.className = "resultado";


    /* BOTÓN SIGUIENTE */

    document.getElementById("botonSiguiente").disabled =
        true;


    /* MENÚ */

    document.querySelectorAll(".menu button").forEach(btn => {
        btn.classList.remove("activo");
    });


    if (boton) {

        boton.classList.add("activo");

    } else {

        document.querySelectorAll(".menu button").forEach(btn => {

            if (btn.textContent.trim().includes(tema.titulo)) {
                btn.classList.add("activo");
            }

        });

    }


    /* CREAR OPCIONES */

    crearOpciones(tema);
}


/* =====================================================
   CREAR OPCIONES EN ORDEN ALEATORIO
===================================================== */

function crearOpciones(tema) {

    const contenedor =
        document.getElementById("opciones");

    contenedor.innerHTML = "";


    /* COPIAMOS LAS RESPUESTAS */

    const opcionesMezcladas =
        [...tema.opciones];


    /* MEZCLAMOS */

    opcionesMezcladas.sort(() => Math.random() - 0.5);


    /* CREAMOS BOTONES */

    opcionesMezcladas.forEach(opcion => {

        const boton =
            document.createElement("button");

        boton.className = "opcion";

        boton.textContent = opcion;


        boton.addEventListener("click", function () {

            comprobarRespuesta(
                opcion,
                boton,
                tema
            );

        });


        contenedor.appendChild(boton);

    });
}


/* =====================================================
   COMPROBAR RESPUESTA
===================================================== */

function comprobarRespuesta(
    respuesta,
    boton,
    tema
) {

    if (respuestaContestada) {
        return;
    }

    respuestaContestada = true;


    const botones =
        document.querySelectorAll(".opcion");


    botones.forEach(btn => {
        btn.disabled = true;
    });


    const resultado =
        document.getElementById("resultado");


    /* ================= CORRECTA ================= */

    if (respuesta === tema.correcta) {

        boton.classList.add("correcta");


        puntos += 10;

        respuestasCorrectas++;

        retosCompletados++;


        document.getElementById("puntos").textContent =
            puntos;


        resultado.textContent =
            "✅ ¡Correcto! +10 puntos 🎉";

        resultado.style.background =
            "#edf9f1";

        resultado.style.color =
            "#287746";

        resultado.classList.add("mostrar");


        /* ANIMACIÓN DE PUNTOS */

        const puntosElemento =
            document.querySelector(".puntos");

        puntosElemento.animate(
            [
                { transform: "scale(1)" },
                { transform: "scale(1.08)" },
                { transform: "scale(1)" }
            ],
            {
                duration: 400
            }
        );


    } else {

        /* ================= INCORRECTA ================= */

        boton.classList.add("incorrecta");


        vidas--;

        if (vidas < 0) {
            vidas = 0;
        }


        retosCompletados++;


        document.getElementById("vidas").textContent =
            vidas;


        resultado.textContent =
            "❌ Incorrecto. La respuesta correcta es: " +
            tema.correcta;


        resultado.style.background =
            "#fff0f0";

        resultado.style.color =
            "#a23c3c";

        resultado.classList.add("mostrar");


        /* MARCAR RESPUESTA CORRECTA */

        botones.forEach(btn => {

            if (btn.textContent === tema.correcta) {
                btn.classList.add("correcta");
            }

        });

    }


    actualizarProgreso();


    document.getElementById("botonSiguiente").disabled =
        false;
}


/* =====================================================
   ACTUALIZAR PROGRESO
===================================================== */

function actualizarProgreso() {

    let porcentaje =
        Math.round(
            (retosCompletados / totalRetos) * 100
        );


    if (porcentaje > 100) {
        porcentaje = 100;
    }


    document.getElementById("porcentaje").textContent =
        porcentaje + "%";


    document.getElementById("retosCompletados").textContent =
        retosCompletados;


    document.getElementById("respuestasCorrectas").textContent =
        respuestasCorrectas;


    /* CÍRCULO */

    const circulo =
        document.getElementById("circuloProgreso");


    const circunferencia = 314;

    const desplazamiento =
        circunferencia -
        (circunferencia * porcentaje / 100);


    circulo.style.strokeDashoffset =
        desplazamiento;


    /* MENSAJE */

    const mensaje =
        document.getElementById("mensajeProgreso");


    if (porcentaje === 0) {

        mensaje.textContent =
            "¡Comienza tu aventura! 🌎";

    } else if (porcentaje < 30) {

        mensaje.textContent =
            "¡Muy buen comienzo! 🚀";

    } else if (porcentaje < 70) {

        mensaje.textContent =
            "¡Sigue explorando! 📚";

    } else if (porcentaje < 100) {

        mensaje.textContent =
            "¡Ya casi terminas! ⭐";

    } else {

        mensaje.textContent =
            "¡Aventura completada! 🏆";

    }

}


/* =====================================================
   ESCUCHAR
===================================================== */

function escuchar() {

    const tema =
        temas[temaActual];


    if (!("speechSynthesis" in window)) {

        alert(
            "Tu navegador no permite reproducir audio."
        );

        return;
    }


    window.speechSynthesis.cancel();


    const voz =
        new SpeechSynthesisUtterance(
            tema.audio
        );


    /* El contenido está en español */

    voz.lang = "es-ES";

    voz.rate = 0.9;

    voz.pitch = 1;


    window.speechSynthesis.speak(voz);
}


/* =====================================================
   SIGUIENTE TEMA
===================================================== */

function siguienteTema() {

    const nombres =
        Object.keys(temas);


    let indice =
        nombres.indexOf(temaActual);


    indice++;


    if (indice >= nombres.length) {

        indice = 0;

    }


    cambiarTema(nombres[indice]);
}


/* =====================================================
   INICIO
===================================================== */

window.addEventListener("load", function () {

    cambiarTema("gastronomia");

    actualizarProgreso();

});